export type TranslationKey = keyof typeof dict.en;

/**
 * ВАЖНО: возвращаемая функция обязана быть стабильной между рендерами.
 * Раньше useT отдавал новую стрелочную функцию на КАЖДЫЙ рендер, а App.tsx держал её
 * в зависимостях useEffect, который запускает анализ ссылки. Получался вечный цикл:
 * анализ завершился -> setInfo -> ре-рендер -> новая t -> эффект перезапустился ->
 * снова анализ. Внешне — «вставил ссылку, и загрузка видео никогда не заканчивается»,
 * а внутри — бесконечный поток 20-секундных запросов в YouTube, который заодно
 * выедал пул потоков бэкенда и подвешивал все остальные страницы, включая настройки.
 */
export function useT() {
  const { settings } = useSettings();
  const lang = settings?.language === "ru" ? "ru" : "en";
  return useCallback(
    (key: TranslationKey) => (dict[lang] as Record<string, string>)[key] ?? dict.en[key],
    [lang]
  );
}
